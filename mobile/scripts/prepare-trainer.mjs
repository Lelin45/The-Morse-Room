import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import sharp from 'sharp';
import { MORSE, getTiming } from '../../audio.js';

const mobile = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(mobile, '..');
const generated = resolve(mobile, 'generated');
const assets = resolve(mobile, 'assets');
await mkdir(generated, { recursive: true });
await mkdir(assets, { recursive: true });

const text = async (name) => (await readFile(resolve(root, name), 'utf8')).replace(/\r\n?/g, '\n');
const styleNames = ['styles.css', 'chat.css', 'practice.css'];
const css = (await Promise.all(styleNames.map(text))).join('\n');
const images = await Promise.all(['google-signin-light.png', 'google-signin-dark.png'].map(async (name) => ({
  name, data: `data:image/png;base64,${(await readFile(resolve(root, name))).toString('base64')}`,
})));
const bundle = await build({
  stdin: { contents: "import '../../app.js'; import '../../mobile-shell.js'; import '../src/web-bridge.js';", resolveDir: resolve(mobile, 'scripts') },
  bundle: true, write: false, format: 'iife', platform: 'browser', target: 'chrome100',
  minify: true, legalComments: 'inline', metafile: true,
});
let javascript = bundle.outputFiles[0].text;
for (const image of images) javascript = javascript.replaceAll(image.name, image.data);
let html = await text('index.html');
html = html.replace('<html lang="en">', '<html lang="en" data-native-app="true">')
  .replace(/<link\b[^>]*rel=["']stylesheet["'][^>]*>\s*/gi, '')
  .replace(/<script\b[^>]*type=["']module["'][^>]*>[\s\S]*?<\/script>\s*/gi, '')
  .replace(/<title>[\s\S]*?<\/title>/i, '<title>Morse Code Nepal</title>')
  .replace('</head>', `<style>${css.replaceAll('</style', '<\\/style')}</style>\n</head>`)
  .replace('</body>', `<script>${javascript.replaceAll('</script', '<\\/script')}</script>\n</body>`);
for (const image of images) html = html.replaceAll(image.name, image.data);
if (/<script\b[^>]*\bsrc=/i.test(html) || /<link\b[^>]*rel=["']stylesheet/i.test(html)) {
  throw new Error('The trainer still contains a network script or stylesheet.');
}
const inputs = Object.keys(bundle.metafile.inputs).map((name) => resolve(mobile, name));
if (inputs.some((name) => /(?:^|[\\/])(?:server|node_modules)[\\/]|(?:^|[\\/])\.env(?:[.\\/]|$)/.test(name))) {
  throw new Error('Only public trainer modules may enter the mobile bundle.');
}
const revision = createHash('sha256').update(html).digest('hex').slice(0, 20);
await writeFile(resolve(generated, 'trainer-html.js'), `// Generated by npm run prepare:trainer.\nexport const trainerRevision = ${JSON.stringify(revision)};\nexport default ${JSON.stringify(html)};\n`);
await writeFile(resolve(generated, 'trainer-html.d.ts'), 'export const trainerRevision: string;\ndeclare const html: string;\nexport default html;\n');
await writeFile(resolve(generated, 'trainer-manifest.json'), JSON.stringify({ revision, bytes: Buffer.byteLength(html), modules: inputs.map((name) => name.replace(root, '').replaceAll('\\', '/')) }, null, 2) + '\n');

// The same timing table drives the trainer and the short opening signal.
const timing = getTiming({ wpm: 24, farnsworth: 24 });
const segments = [{ tone: false, seconds: 0.18 }];
const letters = [];
let cursor = 0.18;
for (const [index, letter] of [...'WELCOME'].entries()) {
  if (index) { segments.push({ tone: false, seconds: timing.characterGap }); cursor += timing.characterGap; }
  letters.push({ letter, start: cursor });
  for (const [markIndex, mark] of [...MORSE[letter]].entries()) {
    if (markIndex) { segments.push({ tone: false, seconds: timing.intraCharacterGap }); cursor += timing.intraCharacterGap; }
    const seconds = mark === '.' ? timing.dit : timing.dah;
    segments.push({ tone: true, seconds }); cursor += seconds;
  }
}
segments.push({ tone: false, seconds: 0.15 }); cursor += 0.15;
const sampleRate = 44100;
const samples = segments.reduce((sum, segment) => sum + Math.round(segment.seconds * sampleRate), 0);
const wav = Buffer.alloc(44 + samples * 2);
wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
wav.writeUInt32LE(sampleRate, 24); wav.writeUInt32LE(sampleRate * 2, 28);
wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(samples * 2, 40);
let sampleOffset = 0;
for (const segment of segments) {
  const count = Math.round(segment.seconds * sampleRate);
  const fade = Math.min(Math.round(0.004 * sampleRate), count / 3);
  for (let index = 0; index < count; index += 1) {
    const envelope = Math.max(0, Math.min(1, index / fade, (count - index - 1) / fade));
    const sample = segment.tone ? Math.sin(2 * Math.PI * 600 * (sampleOffset + index) / sampleRate) * envelope * 0.85 : 0;
    wav.writeInt16LE(Math.round(sample * 32767), 44 + (sampleOffset + index) * 2);
  }
  sampleOffset += count;
}
await writeFile(resolve(assets, 'welcome.wav'), wav);
await writeFile(resolve(generated, 'welcome-timing.json'), JSON.stringify({ duration: cursor, wpm: 24, frequency: 600, letters }, null, 2) + '\n');

// Existing dit/dah brand, drawn as vector artwork and rasterized for Android.
const icon = '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><rect width="1024" height="1024" fill="#05110b"/><circle cx="300" cy="512" r="80" fill="#34f58c"/><rect x="482" y="432" width="322" height="160" rx="80" fill="#34f58c"/></svg>';
const foreground = '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><circle cx="360" cy="512" r="64" fill="#34f58c"/><rect x="500" y="448" width="250" height="128" rx="64" fill="#34f58c"/></svg>';
await sharp(Buffer.from(icon)).png().toFile(resolve(assets, 'icon.png'));
await sharp(Buffer.from(foreground)).png().toFile(resolve(assets, 'adaptive-icon.png'));
await sharp(Buffer.from(foreground.replaceAll('#34f58c', '#ffffff'))).png().toFile(resolve(assets, 'monochrome-icon.png'));
await sharp(Buffer.from(icon)).resize(512, 512).png().toFile(resolve(assets, 'splash-icon.png'));
console.log(`Prepared offline trainer ${revision}: ${Buffer.byteLength(html)} bytes, ${inputs.length} public modules. Opening WELCOME: ${cursor.toFixed(2)} seconds at 24 WPM.`);
