function validateLength(wordLength) {
  if (!Number.isInteger(wordLength) || wordLength < MIN_REAL_WORD_LENGTH || wordLength > MAX_REAL_WORD_LENGTH) {
    throw new RangeError('Choose a whole number of letters per word from 2 to 10.');
  }
}

export function getRealWords(wordLength) {
  validateLength(wordLength);
  return WORDS[wordLength];
}

// Shuffle a copy, so each new session draws its own order without modifying
// the shared dictionary. A session never repeats a word.
export function generateRealWords(wordLength, wordCount, { random = Math.random } = {}) {
  validateLength(wordLength);
  if (!Number.isInteger(wordCount) || wordCount < MIN_REAL_WORD_COUNT || wordCount > MAX_REAL_WORD_COUNT) {
    throw new RangeError('Choose a whole number of words from 2 to 50.');
  }
  if (typeof random !== 'function') throw new TypeError('random must be a function.');
  const words = [...WORDS[wordLength]];
  for (let index = words.length - 1; index > 0; index -= 1) {
    const value = random();
    if (!Number.isFinite(value) || value < 0 || value >= 1) {
      throw new RangeError('random must return a finite number from 0 up to, but not including, 1.');
    }
    const swapIndex = Math.floor(value * (index + 1));
    [words[index], words[swapIndex]] = [words[swapIndex], words[index]];
  }
  return words.slice(0, wordCount);
}

export function generateRealWordGroups({ wordCount, wordLength, random = Math.random }) {
  return generateRealWords(wordLength, wordCount, { random });
}
